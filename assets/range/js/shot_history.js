// Range shot list: client-side session history grouped by club.
//
// The range HUD previously showed only the most recent shot. This keeps an
// in-memory list for the current browser session so the left rail can show
// per-club groups with a pinned average row, matching the desktop app's
// club-averages view.
//
// Deliberately NOT persisted: shot history is user data owned by the desktop
// app (shanktuary_session_history.json). This is a view of the live session
// only, so it must never become a second source of truth.

const MAX_SHOTS = 400;

// Smash values OGC emits when its effective-COR clamp saturates. Mirrors
// OGC_SMASH_AT_COR_FLOOR / OGC_SMASH_AT_COR_CEILING in
// shanktuary_performance_studio.py -- see compute_smash_confidence() for why a
// boundary value carries no information about the strike.
const OGC_SMASH_AT_COR_FLOOR = (1.0 + 0.52) / (1.0 + 0.04593 / 0.200);
const OGC_SMASH_AT_COR_CEILING = (1.0 + 0.83) / (1.0 + 0.04593 / 0.200);
const SMASH_CLAMP_EPSILON = 0.0005;

/**
 * True when a reported smash factor sits on an OGC clamp boundary.
 *
 * The desktop app re-runs OGC's penalty math to detect this. Here we use the
 * cheaper equivalent check the Python side also relies on: a clamped shot must
 * report one of the two boundary smash values. Porting the full band model to
 * JS would duplicate constants that are already flagged as drift-prone.
 */
export function isSmashClamped(smash) {
    if (typeof smash !== 'number' || !isFinite(smash)) return false;
    return Math.abs(smash - OGC_SMASH_AT_COR_FLOOR) < SMASH_CLAMP_EPSILON
        || Math.abs(smash - OGC_SMASH_AT_COR_CEILING) < SMASH_CLAMP_EPSILON;
}

export class ShotHistory {
    constructor() {
        this.shots = [];
        this._seq = 0;
    }

    /**
     * Append a shot. `telemetry` is the object from extractShotTelemetry();
     * carry/offline are the resolved display values (simulated when the Nova
     * payload had none).
     *
     * `isDemo` marks a synthetic shot generated by the Demo button rather than
     * measured by the launch monitor. Demo shots stay in the list so you can
     * see and replay them, but they are excluded from the per-club average and
     * from dispersion/trend statistics -- fabricated numbers must never quietly
     * move a real average.
     */
    add(telemetry, carryYds, offlineYds, isDemo = false) {
        if (!telemetry) return null;
        this._seq += 1;
        const entry = {
            seq: this._seq,
            shotId: telemetry.shotId,
            club: (telemetry.club || 'Unknown').trim(),
            carry: Number(carryYds) || 0,
            offline: Number(offlineYds) || 0,
            ballSpeed: telemetry.ballSpeed,
            smash: telemetry.smash,
            isDemo: !!isDemo,
            telemetry,
        };
        this.shots.push(entry);
        if (this.shots.length > MAX_SHOTS) this.shots.shift();
        return entry;
    }

    /** Measured shots only -- the set every statistic should be computed from. */
    get measured() {
        return this.shots.filter(s => !s.isDemo);
    }

    clear() {
        this.shots = [];
        this._seq = 0;
    }

    get count() { return this.shots.length; }

    find(seq) {
        return this.shots.find(s => s.seq === seq) || null;
    }

    /**
     * Group shots by club.
     *
     * sort: 'recent' -> groups ordered by most recent shot, shots newest first.
     *       'carry'  -> groups ordered by average carry (longest first),
     *                   shots by carry descending.
     */
    grouped(sort = 'recent') {
        const byClub = new Map();
        for (const s of this.shots) {
            if (!byClub.has(s.club)) byClub.set(s.club, []);
            byClub.get(s.club).push(s);
        }

        const groups = [];
        for (const [club, shots] of byClub.entries()) {
            const n = shots.length;
            // Averages come from measured shots only. A demo shot is fabricated
            // telemetry; letting it move the average would silently corrupt the
            // number you actually care about. Groups that are all demo report
            // null averages rather than a made-up figure.
            const real = shots.filter(s => !s.isDemo);
            const realN = real.length;
            const avgCarry = realN ? real.reduce((a, s) => a + s.carry, 0) / realN : null;
            const avgOffline = realN ? real.reduce((a, s) => a + s.offline, 0) / realN : null;
            const ordered = sort === 'carry'
                ? [...shots].sort((a, b) => b.carry - a.carry)
                : [...shots].sort((a, b) => b.seq - a.seq);
            groups.push({
                club,
                shots: ordered,
                count: n,
                measuredCount: realN,
                demoCount: n - realN,
                avgCarry,
                avgOffline,
                lastSeq: Math.max(...shots.map(s => s.seq)),
            });
        }

        groups.sort((a, b) => sort === 'carry'
            ? (b.avgCarry ?? -Infinity) - (a.avgCarry ?? -Infinity)
            : b.lastSeq - a.lastSeq);
        return groups;
    }
}
